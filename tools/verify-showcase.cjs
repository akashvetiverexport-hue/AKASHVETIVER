const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
(async () => {
 const browser = await chromium.launch();
 const page = await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 page.on('response',r=>{if(r.status()>=400)errors.push(r.status()+' '+r.url())});
 await page.goto('http://127.0.0.1:4178',{waitUntil:'networkidle'});
 assert.equal(await page.locator('.occasions,.contact-layout').count(),0);
 assert.equal(await page.locator('#products + #contact').count(),1);
 await page.getByRole('button',{name:'Discuss a bulk order',exact:true}).click();
 assert.ok(await page.locator('#bulk-enquiry-dialog').isVisible());
 await page.keyboard.press('Escape');
 assert.equal(await page.locator('#bulk-enquiry-dialog').isVisible(),false);
 await page.locator('#products').scrollIntoViewIfNeeded();
 await page.mouse.move(0,0);
 await page.waitForFunction(()=>Number(document.querySelector('.showcase-inner')?.dataset.current)>0);
 await page.getByRole('button',{name:'Show Vetiver Peacock (Mayil)',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('.showcase-inner').dataset.current==='2');
 assert.match(await page.locator('.showcase-detail-slide[aria-hidden=false]').textContent(),/Peacock/);
 await page.getByRole('button',{name:'Next product',exact:true}).click();
 assert.equal(await page.locator('.showcase-inner').getAttribute('data-current'),'3');
 for(const width of [1440,768,390,320]){
   await page.setViewportSize({width,height:1000});
   await page.locator('#products').scrollIntoViewIfNeeded();
   await page.waitForTimeout(600);
   assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
   await page.locator('#products').screenshot({path:'.impeccable/review/showcase-'+width+'.png'});
 }
 await page.getByRole('link',{name:'Explore all products',exact:true}).click();
 await page.waitForURL('**/products.html');
 assert.equal(await page.locator('.product-card').count(),12);
 await page.locator('[data-filter=toran]').click();
 assert.equal(await page.locator('.product-card:visible').count(),4);
 await page.locator('[data-product-open]:visible').first().click();
 assert.ok(await page.locator('#product-dialog').isVisible());
 await page.locator('#dialog-enquire').click();
 assert.ok(await page.locator('#enquiry-product').inputValue());
 assert.ok(await page.locator('#bulk-enquiry-dialog').isVisible());
 await page.locator('#enquiry-submit-label').click();
 assert.ok(await page.locator('#enquiry-preview').isVisible());
 await page.keyboard.press('Escape');
 await page.setViewportSize({width:1440,height:1000});
 await page.locator('#products').scrollIntoViewIfNeeded();
 await page.screenshot({path:'.impeccable/review/catalog-desktop.png'});
 await page.goto('http://127.0.0.1:4178/products.html?category=garland',{waitUntil:'networkidle'});
 assert.equal(await page.locator('.product-card:visible').count(),5);
 const reduced=await browser.newPage({reducedMotion:'reduce'});
 await reduced.goto('http://127.0.0.1:4178',{waitUntil:'networkidle'});
 await reduced.locator('#products').scrollIntoViewIfNeeded();
 await reduced.waitForTimeout(3200);
 assert.equal(await reduced.locator('.showcase-inner').getAttribute('data-current'),'0');
 assert.equal(await reduced.getByRole('button',{name:'Pause product slideshow'}).count(),0);
 assert.deepEqual(errors,[]);
 console.log('PASS: synchronized autoplay, thumbnail selection, next control, 4 responsive widths, catalog CTA, filtering, enquiry, reduced motion, no browser errors');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
