const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const base = 'http://127.0.0.1:4178';
(async () => {
  const browser = await chromium.launch();
  const output = path.resolve('.impeccable/review/react-sections');
  fs.mkdirSync(output, { recursive: true });
  const errors = [], report = [];
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => { if (r.status() >= 400) errors.push(r.status() + ' ' + r.url()); });
  await page.goto(base, { waitUntil: 'networkidle' });
  await page.waitForSelector('.bwf');
  assert.equal(await page.locator('.vt-review-empty').count(), 1);
  assert.equal(await page.locator('.vt-review-card').count(), 0);
  assert.equal(await page.locator('#reviews img').count(), 0);
  assert.equal(await page.locator('#footer-root a[href="#"]').count(), 0);
  assert.equal(await page.locator('.bwf').getAttribute('data-motion'), 'idle');
  assert.equal(await page.locator('#feedback-dialog').isVisible(), false);
  for (const width of [1440, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 });
    await page.locator('#reviews').scrollIntoViewIfNeeded();
    await page.waitForTimeout(800);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth <= 1), 'Page overflow: ' + width);
    const grid = await page.locator('.vt-testimonials .vt-section-inner').evaluate(e => getComputedStyle(e).display);
    assert.equal(grid, 'grid', 'Tailwind generated utilities');
    await page.locator('#reviews').screenshot({ path: path.join(output, 'reviews-' + width + '.png') });
    const trigger = page.getByRole('button', { name: 'Add feedback' });
    await trigger.click();
    assert.equal(await page.locator('#feedback-dialog').isVisible(), true);
    assert.ok(await page.locator('#feedback-dialog').evaluate(e => e.scrollWidth <= e.clientWidth + 1));
    for (let n = 0; n < 12; n++) {
      await page.keyboard.press('Tab');
      assert.ok(await page.evaluate(() => document.querySelector('#feedback-dialog').contains(document.activeElement)), 'Focus stays in popup');
    }
    await page.locator('#feedback-dialog').screenshot({ path: path.join(output, 'feedback-' + width + '.png') });
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#feedback-dialog').isVisible(), false);
    assert.ok(await trigger.evaluate(e => e === document.activeElement), 'Focus returns to Add feedback');
    await page.locator('.bwf').scrollIntoViewIfNeeded();
    await page.waitForTimeout(1400);
    const fitted = await page.locator('.bwf-word-in').evaluate(el => el.getBoundingClientRect().width <= el.parentElement.clientWidth + 1);
    assert.ok(fitted, 'Fitted footer wordmark: ' + width);
    await page.locator('.bwf').screenshot({ path: path.join(output, 'footer-' + width + '.png') });
    report.push('Responsive sections and wordmark at ' + width);
  }
  assert.equal(await page.getByRole('button', { name: /pause|resume|play/i }).count(), 0);
  assert.equal(await page.locator('.bwf').getAttribute('data-motion'), 'running');
  await page.locator('.bwf a[href="#feedback-form"]').click();
  assert.equal(await page.locator('#feedback-dialog').isVisible(), true);
  await page.locator('#feedback-name').fill('Test Customer');
  await page.locator('#feedback-content').fill('A private draft for testing, not a public review.');
  await page.locator('input[name="rating"][value="4"]').check();
  await page.getByRole('button', { name: 'Save feedback draft' }).click();
  assert.match(await page.locator('.vt-feedback-status').textContent(), /not been sent or published/);
  assert.equal(await page.locator('.vt-review-card').count(), 0);
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'Add feedback' }).click();
  await page.getByRole('button', { name: 'Restore draft' }).click();
  assert.equal(await page.locator('#feedback-name').inputValue(), 'Test Customer');
  assert.equal(await page.locator('input[name="rating"]:checked').inputValue(), '4');
  await page.getByRole('button', { name: 'Delete saved draft' }).click();
  assert.equal(await page.evaluate(() => localStorage.getItem('vettiver-feedback-draft-v1')), null);
  await page.getByRole('button', { name: 'Close feedback' }).click();
  assert.equal(await page.locator('#feedback-dialog').isVisible(), false);
  await page.getByRole('button', { name: 'Add feedback' }).click();
  assert.equal(await page.locator('#feedback-name').inputValue(), 'Test Customer');
  await page.mouse.click(2, 2);
  assert.equal(await page.locator('#feedback-dialog').isVisible(), false);
  report.push('Draft save/restore/delete; no automatic publication; footer anchor and automatic motion');
  await page.goto(base + '/?ui-demo=testimonials', { waitUntil: 'networkidle' });
  await page.waitForSelector('.vt-review-card');
  assert.equal(await page.locator('.vt-review-card').count(), 3);
  await page.getByRole('button', { name: 'Next review' }).click();
  assert.match(await page.locator('.vt-review-card[aria-hidden="false"]').textContent(), /Sample customer B/);
  assert.equal(await page.getByRole('button', { name: 'Play review slideshow' }).count(), 0);
  report.push('Explicitly labelled preview and accessible manual carousel');
  const reduced = await browser.newPage({ reducedMotion: 'reduce' });
  await reduced.goto(base, { waitUntil: 'networkidle' });
  await reduced.locator('.bwf').scrollIntoViewIfNeeded();
  assert.equal(await reduced.locator('.bwf').getAttribute('data-motion'), 'paused');
  assert.equal(await reduced.getByRole('button', { name: 'Pause light' }).count(), 0);
  report.push('Reduced-motion footer');
  const connected = await browser.newPage();
  await connected.route('**/site-config.js', route => route.fulfill({ contentType: 'application/javascript', body: 'window.VETTIVER_CONFIG={feedbackEndpoint:"/api/feedback"}' }));
  let requestBody;
  await connected.route('**/api/feedback', route => {
    requestBody = route.request().postDataJSON();
    return route.fulfill({ contentType: 'application/json', body: JSON.stringify({ id: 'test-only-id', status: 'pending' }) });
  });
  await connected.goto(base, { waitUntil: 'networkidle' });
  await connected.getByRole('button', { name: 'Add feedback' }).click();
  await connected.locator('#feedback-name').fill('Moderation test');
  await connected.locator('#feedback-content').fill('Mocked request. Never sent to a real service.');
  await connected.locator('input[name="rating"][value="5"]').check();
  await connected.locator('.vt-feedback-consent input').check();
  await connected.getByRole('button', { name: 'Send for approval' }).click();
  await connected.waitForFunction(() => document.querySelector('.vt-feedback-status').textContent.includes('waiting for approval'));
  assert.equal(requestBody.rating, 5);
  assert.equal(requestBody.consentToPublish, true);
  assert.equal(requestBody.status, undefined);
  assert.equal(await connected.locator('.vt-review-card').count(), 0);
  report.push('Mocked API receives name/feedback/rating/consent; response remains pending, never auto-published');
  assert.deepEqual(errors, []);
  fs.writeFileSync(path.join(output, 'report.json'), JSON.stringify({ report, errors }, null, 2));
  console.log(JSON.stringify({ report, errors }, null, 2));
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
