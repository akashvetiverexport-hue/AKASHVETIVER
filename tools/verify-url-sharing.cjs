const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'C:/Users/avina/AppData/Local/npm-cache/_npx/e41f203b7505f1fb/node_modules/playwright-core');
const assert = require('node:assert/strict');
const origin = 'http://127.0.0.1:4178';
(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    for (const width of [1440, 390]) {
      const context = await browser.newContext({ viewport: { width, height: 900 }, reducedMotion: 'reduce' });
      await context.addInitScript(() => {
        Object.defineProperty(navigator, 'share', { configurable: true, value: undefined });
        Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async value => { window.copiedLink = value; } } });
      });
      const page = await context.newPage();
      const errors = [];
      page.on('pageerror', error => errors.push(error.message));
      await page.goto(origin + '/products.html');
      await page.locator('[data-filter=garland]').click();
      assert.equal(new URL(page.url()).searchParams.get('category'), 'garland');
      assert.equal(await page.locator('.product-card:visible').count(), 5);
      await page.locator('#product-search').fill('Royal');
      await page.waitForURL(url => url.searchParams.get('q') === 'Royal');
      assert.equal(new URL(page.url()).searchParams.get('q'), 'Royal');
      await page.reload();
      assert.equal(await page.locator('#product-search').inputValue(), 'Royal');
      assert.equal(await page.locator('.product-card:visible').count(), 1);
      await page.locator('.product-card:visible [data-product-open]').first().click();
      await page.waitForFunction(() => document.querySelector('#product-dialog').open);
      assert.equal(new URL(page.url()).hash, '#product-malai-royal');
      assert.match(await page.title(), /Royal Vetiver Garland/);
      await page.locator('#share-product').click();
      await page.waitForFunction(() => !!window.copiedLink);
      const shared = await page.evaluate(() => window.copiedLink);
      assert.equal(shared, origin + '/products.html#product-malai-royal');
      await page.goBack();
      await page.waitForFunction(() => !document.querySelector('#product-dialog').open);
      assert.equal(new URL(page.url()).searchParams.get('q'), 'Royal');
      await page.goForward();
      await page.waitForFunction(() => document.querySelector('#product-dialog').open);
      await page.keyboard.press('Escape');
      await page.waitForFunction(() => !document.querySelector('#product-dialog').open);
      await page.locator('#share-collection').click();
      assert.equal(new URL(await page.evaluate(() => window.copiedLink)).searchParams.get('q'), 'Royal');
      await page.locator('#product-search').fill('no-such-piece');
      assert.equal(await page.locator('#empty-state').isVisible(), true);
      await page.locator('#clear-filters').click();
      await page.waitForURL(url => !url.search);
      assert.equal(new URL(page.url()).search, '');
      assert.equal(await page.locator('.product-card:visible').count(), 12);
      await page.goBack();
      await page.waitForFunction(() => document.querySelector('#product-search').value === 'no-such-piece');
      await page.goto(shared);
      await page.waitForFunction(() => document.querySelector('#product-dialog').open);
      await page.reload();
      await page.waitForFunction(() => document.querySelector('#product-dialog').open);
      await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => { throw Error('Denied'); } } }));
      await page.locator('#share-product').click();
      assert.equal(await page.locator('#product-share-fallback').isVisible(), true);
      assert.equal(await page.locator('#product-share-url').inputValue(), shared);
      await page.evaluate(() => Object.defineProperty(navigator, 'share', { configurable: true, value: async () => { window.nativeShared = true; } }));
      await page.locator('#share-product').click();
      assert.equal(await page.evaluate(() => window.nativeShared), true);
      await page.evaluate(() => Object.defineProperty(navigator, 'share', { configurable: true, value: async () => { throw new DOMException('Cancelled', 'AbortError'); } }));
      await page.locator('#share-product').click();
      assert.equal(await page.locator('#product-share-fallback').isVisible(), false);
      await page.locator('#dialog-enquire').click();
      assert.equal(await page.locator('#enquiry-product').inputValue(), 'Royal Vetiver Garland');
      assert.equal(await page.locator('#bulk-enquiry-dialog').evaluate(el => el.open), true);
      assert.equal(new URL(page.url()).hash, '');
      await page.locator('.bulk-enquiry-close').click();
      await page.goto(origin + '/products.html?category=garland&q=Royal#product-peacock');
      await page.waitForFunction(() => document.querySelector('#product-dialog').open);
      assert.equal(await page.locator('#dialog-title').textContent(), 'Vetiver Peacock (Mayil)');
      await page.locator('#close-product').click();
      assert.equal(await page.locator('.product-card:visible').count(), 1);
      await page.goto(origin + '/products.html?category=invalid#product-missing');
      assert.equal(await page.locator('.product-card:visible').count(), 12);
      assert.equal(await page.locator('#product-dialog').evaluate(el => el.open), false);
      await page.goto(origin + '/products.html?q=%3Cimg%20src%3Dx%20onerror%3Dalert(1)%3E#%E0%A4%A');
      assert.equal(await page.locator('#empty-state').isVisible(), true);
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
      await page.goto(origin + '/index.html');
      await page.locator('.hero-story-link').click();
      assert.equal(new URL(page.url()).hash, '#contact');
      await page.goBack();
      assert.equal(new URL(page.url()).hash, '');
      await page.locator('.hero-cta').click();
      await page.waitForURL('**/products.html');
      assert.equal(await page.locator('main>section').count(), 1);
      assert.deepEqual(errors, []);
      console.log(`PASS ${width}px: filter/search URL, reload, product links, Back/Forward, sharing/fallback/cancel, enquiry, invalid input, hero navigation`);
      await context.close();
    }
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
