const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const output = path.resolve(__dirname, '../.impeccable/review');
const url = process.env.PREVIEW_URL || 'http://127.0.0.1:4178';

(async () => {
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ headless: true });
  const errors = [];
  const report = { viewports: [], checks: [] };
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`); });
  await page.goto(url, { waitUntil: 'networkidle' });
  await page.evaluate(() => document.fonts.ready);
  await page.waitForTimeout(1800);
  assert.equal(await page.locator('.product-card').count(), 12);
  assert.equal(await page.evaluate(() => gsap.version), '3.14.2');
  const snap = async (name, width, height) => {
    await page.setViewportSize({ width, height });
    await page.goto(url, { waitUntil: 'networkidle' });
    await page.evaluate(() => document.fonts.ready);
    await page.waitForTimeout(2500);
    await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
    const dimensions = await page.evaluate(() => ({ width: innerWidth, scrollWidth: document.documentElement.scrollWidth, hero: document.querySelector('.hero-cta').getBoundingClientRect().bottom }));
    assert.ok(dimensions.scrollWidth <= width + 1, `${name}: horizontal overflow ${dimensions.scrollWidth}`);
    report.viewports.push({ name, ...dimensions });
    assert.ok(dimensions.hero > 0 && dimensions.hero <= height, `${name}: hero CTA outside viewport`);
    await page.screenshot({ path: path.join(output, `${name}-hero.png`) });
    for (let y = 0; y < await page.evaluate(() => document.documentElement.scrollHeight); y += height * .75) {
      await page.evaluate(y => window.scrollTo({ top: y, behavior: 'instant' }), y);
      await page.waitForTimeout(140);
    }
    await page.waitForTimeout(1100);
    await page.evaluate(async () => { await Promise.all([...document.images].filter(img => img.hasAttribute('src')).map(img => img.decode().catch(() => {}))); window.scrollTo({ top: 0, behavior: 'instant' }); });
    await page.waitForTimeout(1200);
    assert.equal(await page.evaluate(() => scrollY), 0);
    await page.screenshot({ path: path.join(output, `${name}.png`), fullPage: true });
  };
  await snap('desktop', 1440, 900);
  await snap('mobile', 390, 844);
  for (const width of [320, 768, 1024, 1280, 1920]) {
    await page.setViewportSize({ width, height: 800 });
    await page.waitForTimeout(250);
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth - innerWidth);
    assert.ok(overflow <= 1, `Overflow at ${width}: ${overflow}`);
    report.viewports.push({ width, overflow });
  }
  await page.setViewportSize({ width: 1440, height: 900 });
  for (const [category, count] of [['garland', 5], ['toran', 4], ['decor', 1], ['ceremony', 2], ['all', 12]]) {
    await page.locator(`[data-filter="${category}"]`).click();
    await page.waitForTimeout(700);
    assert.equal(await page.locator('.product-card:not([hidden])').count(), count, category);
    assert.equal(await page.locator(`[data-filter="${category}"]`).getAttribute('aria-pressed'), 'true');
  }
  await page.locator('#product-search').fill('peacock');
  await page.waitForTimeout(700);
  assert.equal(await page.locator('.product-card:not([hidden])').count(), 1);
  await page.locator('#product-search').fill('nothing-matches-this');
  assert.equal(await page.locator('#empty-state').isVisible(), true);
  await page.locator('#clear-filters').click();
  await page.waitForTimeout(700);
  assert.equal(await page.locator('.product-card:not([hidden])').count(), 12);
  report.checks.push('All category counts, search, empty state and reset');
  const productButton = page.locator('#product-malai-pair .product-image');
  await productButton.click();
  assert.equal(await page.locator('#product-dialog').isVisible(), true);
  assert.equal(await page.locator('#dialog-title').textContent(), 'Wedding Garland Pair');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#product-dialog').isVisible(), false);
  assert.equal(await productButton.evaluate(el => document.activeElement === el), true);
  await productButton.click();
  await page.locator('#dialog-enquire').click();
  assert.equal(await page.locator('#enquiry-product').inputValue(), 'Wedding Garland Pair');
  await page.locator('#enquiry-message').fill('Two pairs for a wedding in Chennai.');
  await page.locator('.enquiry-submit').click();
  assert.match(await page.locator('#prepared-message').inputValue(), /Wedding Garland Pair/);
  assert.match(await page.locator('#prepared-message').inputValue(), /Two pairs/);
  assert.equal(await page.locator('a[href*="919876543210"]').count(), 0);
  report.checks.push('Product dialog, Escape focus return, product enquiry and message preparation');
  await page.locator('.desktop-nav a[href="#reviews"]').click();
  assert.equal(await page.locator('#reviews').isVisible(), true);
  assert.equal(await page.locator('#feedback-form').count(), 1);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#hamburger').click();
  await page.waitForTimeout(700);
  assert.equal(await page.locator('#mobile-menu').isVisible(), true);
  await page.locator('#mobile-menu a[href="#products"]').click();
  await page.waitForTimeout(500);
  assert.equal(await page.locator('#mobile-menu').isVisible(), false);
  assert.equal(await page.locator('#hamburger').getAttribute('aria-expanded'), 'false');
  assert.equal(await page.evaluate(() => document.body.classList.contains('dialog-open')), false);
  report.checks.push('Mobile menu navigation, scroll unlock and reviews anchor');
  const broken = await page.locator('img[src]').evaluateAll(images => images.filter(img => !img.complete || !img.naturalWidth).map(img => img.src));
  assert.deepEqual(broken, []);
  const reduced = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
  await reduced.goto(url, { waitUntil: 'networkidle' });
  assert.equal(await reduced.evaluate(() => ScrollTrigger.getAll().length), 0);
  assert.equal(await reduced.locator('.hero-cta').isVisible(), true);
  await reduced.locator('[data-filter="decor"]').click();
  assert.equal(await reduced.locator('.product-card:not([hidden])').count(), 1);
  report.checks.push('Reduced motion disables all scroll animations while preserving filters');
  const fallback = await browser.newPage();
  await fallback.route('**/assets/vendor/*.js', route => route.abort());
  await fallback.goto(url, { waitUntil: 'networkidle' });
  await fallback.locator('[data-filter="toran"]').click();
  assert.equal(await fallback.locator('.product-card:not([hidden])').count(), 4);
  assert.equal(await fallback.locator('.hero-cta').isVisible(), true);
  report.checks.push('Animation-library failure preserves catalog controls and content');
  const configured = await browser.newPage();
  await configured.route('**/site-config.js', route => route.fulfill({ contentType: 'application/javascript', body: "window.VETTIVER_CONFIG={whatsappNumber:'441234567890'};" }));
  await configured.addInitScript(() => { window.open = value => { window.__openedUrl = value; return null; }; });
  await configured.goto(url, { waitUntil: 'networkidle' });
  await configured.locator('#enquiry-product').selectOption('Green & Gold Garland');
  await configured.locator('#enquiry-message').fill('Wedding & home décor');
  await configured.locator('.enquiry-submit').click();
  const opened = await configured.evaluate(() => window.__openedUrl);
  assert.ok(opened.startsWith('https://wa.me/441234567890?text='));
  assert.match(decodeURIComponent(opened), /Green & Gold Garland/);
  report.checks.push('Configured WhatsApp URL and message encoding (intercepted, no message sent)');
  assert.deepEqual(errors, []);
  report.errors = errors;
  fs.writeFileSync(path.join(output, 'verification.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
